#ifndef __IWDG_H
#define __IWDG_H

#include "sys.h"

/*********************************************************************/
/* 外部接口函数 */

/**
  * @brief  独立看门狗初始化
  * @param  prer: 预分频值 @ref IWDG_Prescaler_Definitions
  * @param  rlr:  重装载值 (0-0xFFF)
  * @note   设置看门狗超时时间：Timeout = rlr * (4 * 2^prer) / LSI_freq
  */
void iwdg_init(uint8_t prer, uint16_t rlr);

/**
  * @brief  喂狗(重置看门狗计数器)
  * @note   必须在超时前调用防止系统复位
  */
void iwdg_feed(void);

#endif /* __IWDG_H */
